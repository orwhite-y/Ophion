#pragma once

#ifndef _VMCALL_REASON_H
#define _VMCALL_REASON_H

enum vm_call_reasons
{
	VMCALL_TEST = 0x01,
	VMCALL_VMXOFF = 0x02,
	VMCALL_EPT_RIP_HOOK = 0x03,
	VMCALL_EPT_UNHOOK_FUNCTION = 0x04,
	VMCALL_EPT_UNHOOK_ALL = 0x05,
	VMCALL_MEMORY_BREAKPOINT_SET = 0x18,
	VMCALL_MEMORY_BREAKPOINT_CLEAR = 0x19,

	// Original UnrealVTDbg wire values. The compatibility layer translates
	// WATCH_* to Ophion 0x18/0x19 and never forwards the other legacy values.
	VMCALL_HIDE_SOFTWARE_BREAKPOINT = 12,
	VMCALL_READ_SOFTWARE_BREAKPOINT = 13,
	VMCALL_READ_EPT_FAKE_PAGE_MEMORY = 14,
	VMCALL_WATCH_WRITES = 15,
	VMCALL_WATCH_READS = 16,
	VMCALL_WATCH_EXECUTES = 17,
	VMCALL_WATCH_DELETE = 18,
	VMCALL_GET_BREAKPOINT = 19,
	VMCALL_INIT_OFFSET = 20,
};


#endif // !_VMCALL_REASON_H
